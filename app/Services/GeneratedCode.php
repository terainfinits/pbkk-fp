        "# ------------------------------------------------------------\n",
        "# 4️⃣ Build a PowerPoint slide with the generated image\n",
        "# ------------------------------------------------------------\n",
        "def create_pptx_with_image(\n",
        "    image_path: Path,\n",
        "    output_path: Path = Path(\"slide_with_image.pptx\"),\n",
        "    slide_width_in: float = 10,  # inches (default PowerPoint width)\n",
        "    slide_height_in: float = 5.625,  # inches (default PowerPoint height)\n",
        "    margin_in: float = 0.5,\n",
        ") -> Path:\n",
        "    \"\"\"Create a PPTX containing a single slide with *image_path*.\n",
        "\n",
        "    The image is added as an independent picture shape so you can move/resize it\n",
        "    later in PowerPoint, Google Slides, or after importing the file into Canva.\n",
        "    \"\"\"\n",
        "\n",
        "    prs = Presentation()\n",
        "    # Set custom slide dimensions if you want – here we keep the defaults\n",
        "    prs.slide_width = Inches(slide_width_in)\n",
        "    prs.slide_height = Inches(slide_height_in)\n",
        "\n",
        "    # Add a blank layout (index 6 is usually the blank slide)\n",
        "    blank_layout = prs.slide_layouts[6]\n",
        "    slide = prs.slides.add_slide(blank_layout)\n",
        "\n",
        "    # ------- Insert the image -----------------------------------\n",
        "    # Compute a nice default size: fill most of the slide while respecting margins\n",
        "    max_width = prs.slide_width - Inches(2 * margin_in)\n",
        "    max_height = prs.slide_height - Inches(2 * margin_in)\n",
        "\n",
        "    # Load the image dimensions (requires Pillow)\n",
        "    from PIL import Image as PilImage\n",
        "    with PilImage.open(image_path) as img:\n",
        "        img_w, img_h = img.size\n",
        "    # Convert pixel size to inches (96 DPI is the PPTX default)\n",
        "    img_w_in = img_w / 96\n",
        "    img_h_in = img_h / 96\n",
        "\n",
        "    # Scale proportionally to fit inside max_width/max_height\n",
        "    scale = min(max_width / Inches(img_w_in), max_height / Inches(img_h_in), 1.0)\n",
        "    final_w = Inches(img_w_in) * scale\n",
        "    final_h = Inches(img_h_in) * scale\n",
        "\n",
        "    # Center the image on the slide\n",
        "    left = (prs.slide_width - final_w) / 2\n",
        "    top = (prs.slide_height - final_h) / 2\n",
        "\n",
        "    slide.shapes.add_picture(str(image_path), left, top, width=final_w, height=final_h)\n",
        "\n",
        "    # Save the deck\n",
        "    prs.save(output_path)\n",
        "    print(f\"💾 PPTX saved to {output_path.resolve()}\")\n",
        "    return output_path\n",
        "\n",
