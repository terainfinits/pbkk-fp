        "# 3️⃣ Helper: generate a single image from a prompt\n",
        "# ------------------------------------------------------------\n",
        "def generate_image(prompt: str, size: str = \"1024x1024\") -> Path:\n",
        "    \"\"\"Generate an image using OpenAI DALL·E.\n",
        "\n",
        "    Args:\n",
        "        prompt: Text description.\n",
        "        size: One of \"256x256\", \"512x512\", \"1024x1024\" (default).\n",
        "\n",
        "    Returns:\n",
        "        Path to the downloaded PNG file.\n",
        "    \"\"\"\n",
        "    # 1️⃣ Call the API\n",
        "    response = openai.Image.create(\n",
        "        prompt=prompt,\n",
        "        n=1,\n",
        "        size=size,\n",
        "        response_format=\"url\",\n",
        "    )\n",
        "\n",
        "    image_url = response[\"data\"][0][\"url\"]\n",
        "    print(f\"🖼️ Image URL: {image_url}\")\n",
        "\n",
        "    # 2️⃣ Download the image\n",
        "    img_data = requests.get(image_url).content\n",
        "    out_path = Path(\"generated.png\")\n",
        "    out_path.write_bytes(img_data)\n",
        "    print(f\"✅ Image saved to {out_path.resolve()}\")\n",
